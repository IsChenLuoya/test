#include <at89c51RC2.h>
#include "Delay.h"
#include "MatrixLED.h"

unsigned char Animation[]={
0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00,
0xF8,0x89,0x89,0xFF,0x00,0x21,0x41,0xFF,0x01,0x01,0x00,0x00,0x1F,0x64,0x84,0x64,
0x1F,0x00,0x70,0x89,0x89,0x89,0x89,0x06,0x00,0x7E,0x81,0x81,0x81,0x81,0x81,0x00,
0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x00
};
void main()
{
	unsigned char i,Offset=3,Count=0;
	MatrixLED_Init();
	while(1)
	{
		for(i=0;i<8;i++)
		{
			MatrixLED_ShowColumn(i,Animation[i+Offset]);
		}
		Count++;
		if(Count>5)
		{
			Count=0;
			Offset++;
			if(Offset>40)
			{
				Offset=0;
			}
		}
	}
}